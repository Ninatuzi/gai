TOPIC_JUDGE_PROMPT = """判断用户的新问题是否属于当前正在讨论的话题模块。

## 当前话题模块
话题: {current_topic}
模块摘要: {current_summary}

## 用户新问题
{user_query}

## 判断规则（适度判定）
- same: 以下情况算 same：
  1. 新问题跟当前话题是同一个具体主题（如都在讨论"析锂"）
  2. 新问题是对当前话题的直接追问或延伸（如"怎么防止？""还有什么原因？"）
  3. 新问题涉及的核心概念在当前模块摘要中明确出现过

- new: 以下情况算 new：
  1. 新问题讨论的是一个不同的具体主题（即使同属锂电池大领域）
  2. 新问题的核心概念在当前模块中没有出现过
  
  例如：当前聊"析锂" → 新问题"磷酸铁锂和三元材料哪个安全" → new（虽然都是锂电池，但具体主题不同）
  例如：当前聊"析锂原因" → 新问题"怎么防止析锂" → same（同一主题的延伸）
  例如：当前聊"正极材料对比" → 新问题"三元材料能量密度" → same（在对比范围内的追问）

思考完成后，最后一行只输出: same 或 new"""

